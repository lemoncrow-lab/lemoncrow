def test_an_edited_file_is_read_again(workspace: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _age(workspace, 600)
    workspace_graph._CACHE.clear()
    assert _edge(build_graph(workspace), "web", "billing", "http").links[0].key == "/invoices/{}"
    reads = _count_reads(monkeypatch)
    api = workspace / "billing" / "billing" / "api.py"

    # Same size, an older (but different) mtime: the stamp changed, so the route is read again.
    api.write_text(BILLING_API.replace("/invoices/", "/invoicez/"), encoding="utf-8")
    os.utime(api, (time.time() - 300, time.time() - 300))
    graph = build_graph(workspace)
    assert reads == ["billing/billing/api.py"]
    assert "http" not in {edge.kind for edge in graph.edges if (edge.source, edge.target) == ("web", "billing")}

    # A different size is read again too.
    reads.clear()
    api.write_text(BILLING_API + "\n\n", encoding="utf-8")
    os.utime(api, (time.time() - 300, time.time() - 300))
    assert _edge(build_graph(workspace), "web", "billing", "http").links[0].key == "/invoices/{}"
    assert reads == ["billing/billing/api.py"]

    # A deleted file drops out of the member's cache.
    (workspace / "billing" / "billing" / "events.py").unlink()
    graph = build_graph(workspace)
    assert "event" not in {edge.kind for edge in graph.edges}
    cached = workspace_graph._CACHE[str(workspace.resolve())]
    billing = next(files for (checkout, relpath), files in cached.items() if relpath == "billing")
    assert "billing/events.py" not in billing and "billing/api.py" in billing


