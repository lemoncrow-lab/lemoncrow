def _edge(graph: WorkspaceGraph, source: str, target: str, kind: str) -> Edge:
    found = [edge for edge in graph.edges if (edge.source, edge.target, edge.kind) == (source, target, kind)]
    assert len(found) == 1, f"{source} -> {target} {kind}: {[(e.source, e.target, e.kind) for e in graph.edges]}"
    return found[0]


def _hit(report: ImpactReport, repo: str) -> ImpactHit:
    found = [hit for hit in report.reached if hit.repo == repo]
    assert found, f"{repo} not reached: {[hit.repo for hit in report.reached]}"
    return found[0]


