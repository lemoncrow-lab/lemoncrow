def test_http_paths_are_normalized_before_matching() -> None:
    route = workspace_graph._route_segments
    call = workspace_graph._call_segments
    for declared in ("/invoices/{id}", "/invoices/:id", "/invoices/<int:id>", "GET /invoices/{id}"):
        assert route(declared) == ("invoices", "{}")
    assert call("/invoices/${id}", False) == (("invoices", "{}"), False, None)
    assert call("{BASE}/invoices/{inv}", False) == (("invoices", "{}"), True, None)
    assert call("${API}/invoices/1?x=2", False) == (("invoices", "1"), True, None)
    assert call("https://billing/invoices/7", False) == (("invoices", "7"), False, "billing")
    assert call("https://user@Billing.Internal:8443/invoices/7", False) == (
        ("invoices", "7"),
        False,
        "billing.internal",
    )
    assert call("invoice.paid", False) is None
    assert route("/health") is None and route("/{id}") is None


