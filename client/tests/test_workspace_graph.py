def _env(root: Path, tmp_path: Path) -> dict[str, str]:
    return {
        "LEMONCROW_WORKSPACE_ROOT": str(root),
        "LEMONCROW_HOME": str(tmp_path / "state"),
        "HOME": str(tmp_path),
        "LEMONCROW_RUNTIME_TRACE": "off",
    }


def test_lite_graph_workspace_and_impact_in_a_folder_root(workspace: Path, tmp_path: Path) -> None:
    server = LiteMcp(environment=_env(workspace, tmp_path))
    try:
        graph = server.call("graph", {"kind": "workspace"})
        assert not graph["isError"]
        edges = graph["structuredContent"]["edges"]
        package = next(edge for edge in edges if (edge["source"], edge["kind"]) == ("bazaar", "package"))
        assert package["links"][0]["consumer"]["path"] == "bazaar/pyproject.toml"
        assert "bazaar -> billing  http  low" in graph["content"][0]["text"]

        reached = server.call("graph", {"kind": "impact", "paths": ["billing/billing/api.py", "elsewhere.txt"]})
        assert not reached["isError"]
        payload = reached["structuredContent"]
        assert payload["changed"] == [{"repo": "billing", "files": ["billing/billing/api.py"]}]
        assert payload["outside"] == ["elsewhere.txt"]
        bazaar = next(hit for hit in payload["reached"] if hit["repo"] == "bazaar")
        assert bazaar["direct"] is True
        http = next(edge for edge in bazaar["edges"] if edge["kind"] == "http")
        assert http["links"][0]["provider"]["path"] == "billing/billing/api.py"
        assert "not in a repository of this root: elsewhere.txt" in reached["content"][0]["text"]

        # No paths: the members' working-tree changes (none here).
        assert server.call("graph", {"kind": "impact"})["structuredContent"]["changed"] == []
        # The index-backed kinds still route as before.
        assert server.call("graph", {"kind": "map"})["structuredContent"]["kind"] == "map"
    finally:
        server.close()


def test_lite_graph_in_a_plain_repository(tmp_path: Path) -> None:
    repo = _repo(tmp_path / "solo", {"pyproject.toml": '[project]\nname = "solo"\n', "solo/__init__.py": ""})
    server = LiteMcp(environment=_env(repo, tmp_path))
    try:
        graph = server.call("graph", {"kind": "workspace"})["structuredContent"]
        assert [member["repo"] for member in graph["members"]] == ["."]
        assert graph["edges"] == []
        (repo / "solo" / "__init__.py").write_text("x = 1\n", encoding="utf-8")
        reached = server.call("graph", {"kind": "impact"})["structuredContent"]
        assert reached["changed"] == [{"repo": ".", "files": ["solo/__init__.py"]}]
        assert reached["reached"] == []
    finally:
        server.close()
