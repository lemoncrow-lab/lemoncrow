def _age(root: Path, seconds: int = 600) -> None:
    """Move every working-tree file's mtime into the past, beyond the racy-read window."""

    when = time.time() - seconds
    for path in root.rglob("*"):
        if path.is_file() and not path.is_symlink() and ".git" not in path.relative_to(root).parts:
            os.utime(path, (when, when))


def _count_reads(monkeypatch: pytest.MonkeyPatch) -> list[str]:
    reads: list[str] = []
    original = workspace_graph._read_entry

    def counting(repo: Any, path: str, root: Path, stamp: tuple[int, int, int, int]) -> Any:
        reads.append(repo.prefixed(path))
        return original(repo, path, root, stamp)

    monkeypatch.setattr(workspace_graph, "_read_entry", counting)
    return reads


def test_cached_and_uncached_scans_are_identical(workspace: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _age(workspace)
    workspace_graph._CACHE.clear()
    reads = _count_reads(monkeypatch)

    cold = build_graph(workspace).to_dict()
    cold_impact = impact(workspace, {"billing": ["billing/api.py"]}).to_dict()
    assert reads
    reads.clear()

    warm = build_graph(workspace).to_dict()
    warm_impact = impact(workspace, {"billing": ["billing/api.py"]}).to_dict()

    assert reads == []  # nothing changed: every file's facts were reused
    assert warm == cold
    assert warm_impact == cold_impact
    workspace_graph._CACHE.clear()
    assert build_graph(workspace).to_dict() == cold


