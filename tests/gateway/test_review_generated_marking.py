"""What may be accepted by rule: only a file the trusted base marked generated, and only lockfile version moves.

These run the real analyses (``git check-attr`` on a real repository, ``derive_dependency_units`` on real lockfile
pairs) rather than hand-written facts, because the rule is only as good as what feeds it.
"""

