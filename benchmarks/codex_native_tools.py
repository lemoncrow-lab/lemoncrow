"""Making Codex run on LemonCrow's toolset instead of its own.

Codex has no "substitute my toolset" switch -- MCP servers are purely additive,
so by default the model is offered both Codex's natives and the LemonCrow tools
that duplicate them and picks whichever it likes. Everything here is the
machinery for removing that choice, shared by the codebench driver
(``benchmarks/codebench/run.py``) and the Harbor arms
(``benchmarks/harbor/codex_agent.py``) so the two benchmarks cannot drift.

Verified against the real request prefix on codex-cli 0.145.0 by reading the
``additional_tools`` item off the ``codex/responses`` websocket: with these
settings Codex's native tool catalog drops from ~32KB to ~12KB and no shell,
web, browser, computer, image, goal, plugin or skill tool is offered.

Two limits that config cannot fix on 0.145.0, both deliberate to state plainly:

* ``apply_patch``, ``update_plan`` and ``view_image`` have no off switch, so
  they stay in the catalog. :func:`codex_native_calls` is the answer to that --
  it proves after the fact that the model never actually reached for one.
* Codex's own ~7.7KB system prompt can only be appended to, never replaced, so
  the LemonCrow persona rides on top of it rather than in place of it.
"""

from __future__ import annotations

import collections
import contextlib
import json
import re
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

# Codex features whose tools LemonCrow replaces or does not use. Every name is a
# real flag from `codex features list`; unknown keys are silently ignored by
# Codex, so a typo here degrades into "native tool still offered" -- which is
# why codex_native_calls() exists as the backstop rather than trusting this list.
CODEX_DISABLED_FEATURES: tuple[str, ...] = (
    "shell_tool",  # lc.bash replaces it
    "unified_exec",  # the other half of native exec
    "multi_agent",  # LemonCrow role agents replace the spawn_agent family
    "browser_use",
    "computer_use",
    "in_app_browser",
    "image_generation",
    "goals",
    "apps",
    "plugins",
    "skill_search",
    "tool_suggest",
    "memories",
    "workspace_dependencies",
)
# Not a bool and not under [features]: web search is a top-level mode string.
CODEX_WEB_SEARCH_MODE = "disabled"

# `-c key=value` overrides equivalent to the config file above, for callers that
# drive Codex by command line rather than by writing a config.toml.
CODEX_CONFIG_OVERRIDES: tuple[tuple[str, str], ...] = (
    *((f"features.{name}", "false") for name in CODEX_DISABLED_FEATURES),
    ("web_search", f'"{CODEX_WEB_SEARCH_MODE}"'),
)

# Codex 0.145.0 runs "code mode": the model gets ONE tool, `exec`, which
# evaluates JavaScript that calls everything else as `tools.<name>(...)` --
# LemonCrow's MCP tools included, as `tools.mcp__lc__*`. So an `exec` call is
# not itself a native-tool use; what matters is which names its script invokes.
_TOOL_CALL_RE = re.compile(r"\btools\.([A-Za-z0-9_]+)\s*\(|tools\[[\"']([A-Za-z0-9_]+)[\"']\]")
_LC_TOOL_PREFIX = "mcp__lc__"
_CALL_TYPES = ("function_call", "custom_tool_call", "local_shell_call")


def codex_persona_instructions(persona: str, repo_root: Path | None = None) -> str:
    """Render *persona* (e.g. ``lemoncrow:auto``) as Codex ``developer_instructions``.

    Same text a real ``scripts/install_codex.sh`` writes into the role's agent
    TOML -- crucially with tool names in the ``lc.`` spelling Codex exposes,
    which the generic ``AGENTS.lemoncrow.md`` pointer file does not carry.
    """
    import tomllib

    from lemoncrow.core.capabilities.workspace_host_overrides import write_codex_agents

    role = persona.split(":", 1)[-1]
    dest = Path(tempfile.mkdtemp(prefix=f"codex-persona-{role}-"))
    written = write_codex_agents(dest, model_workspace=None, repo_root=repo_root or REPO_ROOT, role_ids=(role,))
    return str(tomllib.loads(written[0].read_text(encoding="utf-8"))["developer_instructions"])


def codex_config_toml(persona: str, lemoncrow_bin: str, repo_root: Path | None = None) -> str:
    """A whole ``$CODEX_HOME/config.toml`` pinning Codex to LemonCrow's toolset.

    Preferred over a pile of ``-c`` flags wherever the caller controls
    ``CODEX_HOME`` (containers), because it also survives any Codex subprocess
    the run spawns.
    """
    lines = [
        "# Generated by benchmarks/codex_native_tools.py -- do not edit by hand.",
        f"developer_instructions = {json.dumps(codex_persona_instructions(persona, repo_root))}",
        f'web_search = "{CODEX_WEB_SEARCH_MODE}"',
        "",
        "[features]",
        *(f"{name} = false" for name in CODEX_DISABLED_FEATURES),
        "",
        "[mcp_servers.lc]",
        f"command = {json.dumps(lemoncrow_bin)}",
        'args = ["mcp", "--host", "codex"]',
        "",
    ]
    return "\n".join(lines)


def codex_native_calls(sessions_root: Path) -> collections.Counter[str]:
    """Count native (non-LemonCrow) tool invocations in Codex session rollouts.

    *sessions_root* is a ``$CODEX_HOME`` or any directory containing rollout
    ``*.jsonl`` files. An empty result is the proof that a run stayed on
    LemonCrow's tools; anything else names exactly what leaked.
    """
    seen: collections.Counter[str] = collections.Counter()
    for path in sessions_root.rglob("*.jsonl"):
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            if '"function_call"' not in line and '"custom_tool_call"' not in line:
                continue
            with contextlib.suppress(Exception):
                payload = json.loads(line).get("payload", {})
                if payload.get("type") not in _CALL_TYPES:
                    continue
                name = str(payload.get("name"))
                if name != "exec":
                    # A direct call to something other than the code-mode host.
                    seen[name] += 1
                    continue
                script = str(payload.get("input") or payload.get("arguments") or "")
                for dotted, bracketed in _TOOL_CALL_RE.findall(script):
                    called = dotted or bracketed
                    if not called.startswith(_LC_TOOL_PREFIX):
                        seen[called] += 1
    return seen
