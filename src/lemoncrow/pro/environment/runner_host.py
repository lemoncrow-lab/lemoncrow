"""What the environment runners need from the product that runs them.

The runners (:mod:`lemoncrow.pro.environment.runners`) live in the environment core, which
imports neither product. A product hands them its pieces through the run context: the
context's ``runner_host`` provides the snapshot materializer, the hermetic fetch/build/run
stages, run evidence protection and runtime observation (Review's is
``lemoncrow.pro.capabilities.review.runner_host``). The context, runtime and surface
types below are the shapes the runners read; a product's own types satisfy them.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping
from pathlib import Path
from typing import Any, Protocol


class RunnerHost(Protocol):
    """The product pieces a runner calls; names and signatures are the product's own."""

    # Snapshot: one exact side of a change, materialized into a fresh directory.
    @property
    def ReviewSnapshotUnavailable(self) -> type[Exception]: ...
    @property
    def materialize_review_side(self) -> Callable[..., Any]: ...
    @property
    def revision_side_identity(self) -> Callable[[Any, str], object]: ...

    # Hermetic stages and their policy (fetch, offline build, offline run with recording sinks).
    @property
    def REPRODUCE_COMMAND(self) -> str: ...
    @property
    def DeclaredDependencies(self) -> type[Any]: ...
    @property
    def HermeticPolicy(self) -> Callable[[], Any]: ...
    @property
    def HermeticRefused(self) -> type[Exception]: ...
    @property
    def HermeticUnavailable(self) -> type[Exception]: ...
    @property
    def ProvisionedDependencies(self) -> Callable[[], Any]: ...
    @property
    def RecordingSinks(self) -> Any: ...
    @property
    def SandboxView(self) -> Callable[..., Any]: ...
    @property
    def build_execution_result(self) -> Callable[..., Any]: ...
    @property
    def executor_image_digest(self) -> Callable[[], str]: ...
    @property
    def kernel_release(self) -> Callable[[], str]: ...
    @property
    def lockfile_digest(self) -> Callable[[Path], str]: ...
    @property
    def probe_executables(self) -> Callable[..., Any]: ...
    @property
    def provision_declared_dependencies(self) -> Callable[..., Any]: ...
    @property
    def provision_dependencies(self) -> Callable[..., Any]: ...
    @property
    def sinks_available(self) -> Callable[[], bool]: ...
    @property
    def workspace_digest(self) -> Callable[..., str]: ...

    # Run evidence: redaction and the artifact store.
    @property
    def RunArtifactStore(self) -> Any: ...
    @property
    def protect_bytes(self) -> Callable[..., Any]: ...
    @property
    def protect_execution_result(self) -> Callable[..., Any]: ...
    @property
    def protect_text(self) -> Callable[..., Any]: ...

    # Runtime side-effect observation (a trusted-only spec).
    @property
    def ObservationSetup(self) -> Any: ...
    @property
    def ObservationSpec(self) -> type[Any]: ...
    @property
    def build_observation(self) -> Callable[..., Any]: ...
    @property
    def workspace_change_rows(self) -> Callable[..., Any]: ...

    # Container image contents: what a built root filesystem archive holds.
    @property
    def inspect_container_archive(self) -> Callable[[bytes], dict[str, Any]]: ...


class RunRevision(Protocol):
    @property
    def id(self) -> str: ...
    @property
    def review_id(self) -> str: ...


class RunRuntime(Protocol):
    """One configured runtime: which runner, and its values."""

    @property
    def id(self) -> str: ...
    @property
    def runner(self) -> str: ...
    @property
    def values(self) -> Mapping[str, Any]: ...
    def string(self, key: str, default: str = "") -> str: ...
    def strings(self, key: str) -> tuple[str, ...]: ...


class RunConfig(Protocol):
    def runtime(self, runtime_id: str) -> RunRuntime | None: ...


class RunSurface(Protocol):
    """The surface a run exercises."""

    @property
    def id(self) -> str: ...
    @property
    def provider(self) -> str: ...
    @property
    def kind(self) -> str: ...
    @property
    def runtime(self) -> str: ...
    @property
    def capabilities(self) -> tuple[str, ...]: ...
    @property
    def metadata(self) -> Mapping[str, Any]: ...


class RunContext(Protocol):
    """One run's inputs: where the change lives, its configuration and the product's host."""

    @property
    def repo_root(self) -> Path: ...
    @property
    def store_root(self) -> Path: ...
    @property
    def source_root(self) -> Path | None: ...
    @property
    def revision(self) -> RunRevision: ...
    @property
    def config(self) -> RunConfig: ...
    @property
    def store(self) -> Any: ...
    @property
    def execution(self) -> Any: ...
    @property
    def runner_host(self) -> RunnerHost: ...


__all__ = ["RunConfig", "RunContext", "RunRevision", "RunRuntime", "RunSurface", "RunnerHost"]
