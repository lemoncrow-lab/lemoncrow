import { cva, type VariantProps } from "class-variance-authority";
import type { HTMLAttributes } from "react";

import { cn } from "../../lib/utils";

/**
 * The Hunk: LemonCrow's one container motif. A hairline frame, an optional mono `@@ LABEL @@` header
 * strip, an optional footer strip, and rows that may carry a 3px rail in a semantic colour. The
 * classes (`hunk`, `hunk-head`, `hunk-label`, `hunk-foot`) live in src/design/lc-components.css;
 * these are the typed React wrappers. Nest at most two deep: a row is a hairline plus an optional
 * rail, not another frame.
 */
export function Hunk({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return <div className={cn("hunk", className)} {...props} />;
}

/** The header strip. Left slot: the object's name (HunkLabel). Right slot: at most one badge or meta string. */
export function HunkHead({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return <div className={cn("hunk-head", className)} {...props} />;
}

/** The label inside a header strip; the `@@ ... @@` markers are generated by CSS and are not announced. */
export function HunkLabel({ className, ...props }: HTMLAttributes<HTMLSpanElement>) {
  return <span className={cn("hunk-label", className)} {...props} />;
}

export function HunkBody({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return <div className={cn("p-3", className)} {...props} />;
}

export function HunkFoot({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return <div className={cn("hunk-foot", className)} {...props} />;
}

/** A row keeps a 3px left rail only to carry state (severity, kind, review status); always redundant with a text badge. */
export const hunkRowVariants = cva("", {
  variants: {
    rail: {
      none: "",
      p0: "border-l-rail border-l-p0-solid",
      p1: "border-l-rail border-l-p1-solid",
      p2: "border-l-rail border-l-p2-solid",
      ok: "border-l-rail border-l-ok-solid",
      neutral: "border-l-rail border-l-border",
    },
  },
  defaultVariants: { rail: "none" },
});

export type HunkRail = NonNullable<VariantProps<typeof hunkRowVariants>["rail"]>;

export function HunkRow({ className, rail, ...props }: HTMLAttributes<HTMLDivElement> & VariantProps<typeof hunkRowVariants>) {
  return <div className={cn(hunkRowVariants({ rail }), className)} {...props} />;
}
