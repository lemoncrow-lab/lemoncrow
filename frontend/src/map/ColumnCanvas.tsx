import { memo, useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState, type KeyboardEvent } from "react";
import { ChevronRight, Folder, RefreshCcw, Sparkles } from "lucide-react";

import { Button } from "../components/ui/button";
import { COLUMN_LAYOUT, type ColumnCard, type ColumnEdge, type ColumnModel } from "./columnModel";
import type { MapActivityKind } from "./types";
import "./map.css";

export interface ColumnActivity {
  kind: MapActivityKind;
  sessions: string[];
}

export interface ColumnCanvasProps {
  model: ColumnModel;
  selectedId: string | null;
  /** Live overlay per card id. */
  activity?: ReadonlyMap<string, ColumnActivity>;
  onSelect(id: string | null): void;
  onOpen(id: string): void;
  onToggleFold(id: string): void;
  onWidth(width: number): void;
  ariaLabel?: string;
}

type CardState = "idle" | "selected" | "neighbor" | "dim";

function plural(count: number, one: string, many = one + "s"): string {
  return count.toLocaleString() + " " + (count === 1 ? one : many);
}

function stageY(value: number): number {
  return value - COLUMN_LAYOUT.header;
}

function columnTitle(model: ColumnModel, index: number): string {
  const column = model.columns[index];
  if (column.unlinked) return "No links";
  const linked = model.columns.filter((item) => !item.unlinked).length;
  if (linked === 1) return "Modules";
  if (index === 0) return "Uses the others";
  if (index === linked - 1) return "Used by the others";
  return "";
}

const ColumnCardView = memo(function ColumnCardView({
  card,
  state,
  activity,
  onSelect,
  onOpen,
  onHover,
  onToggleFold,
  registerRef,
}: {
  card: ColumnCard;
  state: CardState;
  activity: ColumnActivity | undefined;
  onSelect(id: string): void;
  onOpen(id: string): void;
  onHover(id: string | null): void;
  onToggleFold(id: string): void;
  registerRef(id: string, element: HTMLButtonElement | null): void;
}) {
  const style = { left: card.x, top: stageY(card.y), width: card.w, height: card.h, justifyContent: "flex-start", gap: 3, paddingTop: 7 };
  const name = card.fold ? `${card.label}/` : card.label;
  const description = card.fold
    ? `${name}, ${plural(card.members.length, "module")} folded`
    : `${name}, ${plural(card.files, "file")}${card.changed ? `, ${card.changed} uncommitted` : ""}`;
  return (
    <Button
      unstyled
      ref={(element: HTMLButtonElement | null) => registerRef(card.id, element)}
      className="rm-card"
      data-node-id={card.id}
      data-variant={card.fold ? "fold" : "module"}
      data-state={state}
      data-activity={activity?.kind}
      aria-pressed={state === "selected"}
      aria-label={description}
      title={card.fold ? card.members.join("\n") : card.members[0] || "Repository root"}
      style={style}
      onClick={() => (card.fold ? onToggleFold(card.id) : onSelect(card.id))}
      onDoubleClick={() => (card.fold ? onToggleFold(card.id) : onOpen(card.id))}
      onMouseEnter={() => onHover(card.id)}
      onMouseLeave={() => onHover(null)}
      onFocus={() => onHover(null)}
    >
      <span className="rm-card-row">
        {card.fold ? <ChevronRight size={13} aria-hidden="true" className="shrink-0" /> : <Folder size={13} aria-hidden="true" className="shrink-0 text-muted-foreground" />}
        <span className="rm-card-name">{name}</span>
        <span className="rm-trailing">
          {activity && activity.sessions.length > 0 && (
            <span className="rm-sessions" title={`Agent activity: ${activity.sessions.join(", ")}`}>
              {activity.sessions.slice(0, 3).map((mark) => <i key={mark}>{mark}</i>)}
            </span>
          )}
          {card.changed > 0 && <span className="rm-changed" title={`${plural(card.changed, "uncommitted file")}`}>{card.changed}</span>}
        </span>
      </span>
      <span className="rm-card-meta">
        {card.fold ? <span>{plural(card.members.length, "module")}</span> : null}
        <span>{plural(card.files, "file")}</span>
        {card.symbols > 0 && <span>{plural(card.symbols, "symbol")}</span>}
      </span>
      {card.purpose && (
        <span className="rm-purpose" title={card.purposeGenerated ? `Generated by a model on request: ${card.purpose}` : undefined}>
          {card.purposeGenerated && <Sparkles size={9} aria-hidden="true" className="mr-1 inline align-baseline" />}
          {card.purpose}
        </span>
      )}
    </Button>
  );
});

function edgeLabel(edge: ColumnEdge): string {
  const kinds = Object.entries(edge.kinds).sort((a, b) => b[1] - a[1]);
  const top = kinds[0];
  return top ? `${top[0]} ×${edge.weight}` : `×${edge.weight}`;
}

export default function ColumnCanvas({
  model,
  selectedId,
  activity,
  onSelect,
  onOpen,
  onToggleFold,
  onWidth,
  ariaLabel = "Module map",
}: ColumnCanvasProps) {
  const scrollRef = useRef<HTMLDivElement>(null);
  const cardRefs = useRef(new Map<string, HTMLButtonElement>());
  const [hoverId, setHoverId] = useState<string | null>(null);

  useLayoutEffect(() => {
    const element = scrollRef.current;
    if (!element) return;
    onWidth(element.clientWidth);
    if (typeof ResizeObserver === "undefined") return;
    let frame = 0;
    const observer = new ResizeObserver(() => {
      window.cancelAnimationFrame(frame);
      frame = window.requestAnimationFrame(() => onWidth(element.clientWidth));
    });
    observer.observe(element);
    return () => {
      window.cancelAnimationFrame(frame);
      observer.disconnect();
    };
  }, [onWidth]);

  useEffect(() => {
    if (!selectedId) return;
    const element = cardRefs.current.get(selectedId);
    if (element && typeof element.scrollIntoView === "function") element.scrollIntoView({ block: "nearest", inline: "nearest" });
  }, [selectedId]);

  const registerRef = useCallback((id: string, element: HTMLButtonElement | null) => {
    if (element) cardRefs.current.set(id, element);
    else cardRefs.current.delete(id);
  }, []);

  const activeId = hoverId ?? selectedId;
  const neighborIds = useMemo(() => {
    if (!activeId) return null;
    return new Set([activeId, ...(model.neighbors.get(activeId) ?? [])]);
  }, [activeId, model.neighbors]);

  const edgeState = (edge: ColumnEdge): "idle" | "active" | "dim" | "hidden" => {
    if (activeId) {
      if (edge.from === activeId || edge.to === activeId) return "active";
      return edge.resting ? "dim" : "hidden";
    }
    return edge.resting ? "idle" : "hidden";
  };
  const order = { hidden: 0, dim: 1, idle: 2, active: 3 } as const;
  const visible = model.edges
    .map((edge) => ({ edge, state: edgeState(edge) }))
    .filter((item) => item.state !== "hidden")
    .sort((a, b) => order[a.state] - order[b.state]);
  const labels = visible
    .filter((item) => item.state === "active")
    .sort((a, b) => b.edge.weight - a.edge.weight)
    .slice(0, 12);

  const cardState = (id: string): CardState => {
    if (id === selectedId) return "selected";
    if (!neighborIds) return "idle";
    return neighborIds.has(id) ? "neighbor" : "dim";
  };

  const move = (event: KeyboardEvent<HTMLDivElement>) => {
    if (!["ArrowUp", "ArrowDown", "ArrowLeft", "ArrowRight", "Enter"].includes(event.key)) return;
    const current = selectedId ? model.cardById.get(selectedId) : undefined;
    if (event.key === "Enter") {
      if (current) {
        event.preventDefault();
        if (current.fold) onToggleFold(current.id);
        else onOpen(current.id);
      }
      return;
    }
    event.preventDefault();
    let target: string | undefined;
    if (!current) {
      target = model.columnOrder.find((column) => column.length)?.[0];
    } else if (event.key === "ArrowUp" || event.key === "ArrowDown") {
      const column = model.columnOrder[current.column];
      const index = column.indexOf(current.id) + (event.key === "ArrowDown" ? 1 : -1);
      target = column[Math.max(0, Math.min(column.length - 1, index))];
    } else {
      const step = event.key === "ArrowRight" ? 1 : -1;
      for (let index = current.column + step; index >= 0 && index < model.columnOrder.length; index += step) {
        const column = model.columnOrder[index];
        if (!column.length) continue;
        const center = current.y + current.h / 2;
        target = [...column].sort((a, b) => {
          const p = model.cardById.get(a)!;
          const q = model.cardById.get(b)!;
          return Math.abs(p.y + p.h / 2 - center) - Math.abs(q.y + q.h / 2 - center);
        })[0];
        break;
      }
    }
    if (target) {
      onSelect(target);
      window.requestAnimationFrame(() => cardRefs.current.get(target!)?.focus({ preventScroll: true }));
    }
  };

  const stageHeight = stageY(model.height);

  return (
    <div ref={scrollRef} className="rm-canvas h-full w-full" role="group" aria-label={ariaLabel} onKeyDown={move}>
      <div className="rm-lane-headers" style={{ width: model.width }}>
        {model.columns.map((column) => (
          <div key={column.index} className="rm-lane-title" style={{ left: column.x + 4, width: column.w }}>
            {columnTitle(model, column.index)}
            <small>{plural(column.count, "module")}</small>
          </div>
        ))}
      </div>
      <div
        className="relative"
        style={{ width: model.width, height: stageHeight }}
        onClick={(event) => {
          if (event.target === event.currentTarget || (event.target as HTMLElement).classList?.contains("rm-lane-band")) onSelect(null);
        }}
      >
        {model.columns.map((column) => (
          <div key={column.index} className="rm-lane-band" data-lane={column.unlinked ? "unlinked" : "column"} style={{ left: column.x - 10, width: column.w + 20, top: 0, bottom: 8 }} />
        ))}
        {model.cycles.map((group) => (
          <div
            key={group.id}
            className="rm-cycle"
            style={{ left: group.x, top: stageY(group.y), width: group.w, height: group.h }}
            title="These modules depend on each other; their order inside the cycle is arbitrary."
          >
            <RefreshCcw size={10} aria-hidden="true" /> cycle · {group.members.length} modules
          </div>
        ))}
        <svg className="rm-edges" width={model.width} height={stageHeight} aria-hidden="true">
          <g transform={`translate(0,${-COLUMN_LAYOUT.header})`}>
            {visible.map(({ edge, state }) => (
              <g key={edge.key}>
                <path className="rm-edge" d={edge.d} data-kind="calls" data-state={state} strokeWidth={state === "active" ? edge.width + 0.3 : edge.width} />
                <path className="rm-arrow" d={edge.arrow} data-kind="calls" data-state={state} />
              </g>
            ))}
            {labels.map(({ edge }) => {
              const text = edgeLabel(edge);
              const width = text.length * 5.6 + 14;
              return (
                <g key={edge.key} className="rm-edge-label" transform={`translate(${edge.labelX - width / 2},${edge.labelY - 9})`}>
                  <rect width={width} height={18} rx={9} />
                  <text x={width / 2} y={12.5} textAnchor="middle">{text}</text>
                </g>
              );
            })}
          </g>
        </svg>
        {model.cards.map((card) => (
          <ColumnCardView
            key={card.id}
            card={card}
            state={cardState(card.id)}
            activity={activity?.get(card.id)}
            onSelect={onSelect}
            onOpen={onOpen}
            onHover={setHoverId}
            onToggleFold={onToggleFold}
            registerRef={registerRef}
          />
        ))}
      </div>
    </div>
  );
}
