export interface ModuleLink {
  id: string;
  label: string;
  weight: number;
  kinds: Record<string, number>;
}

export type InspectorSubject =
  | { kind: "file" | "symbol"; node: CodeMapNode; range: readonly [number, number] | null }
  | { kind: "module"; module: CodeModule; usedBy: ModuleLink[]; uses: ModuleLink[] };

export type ReviewScope = { session: string } | { paths: string[] };

const ACTIVITY_TONE: Record<CodeMapActivityKind, { dot: string; label: string }> = {
  search: { dot: "bg-violet-300", label: "Searched" },
  read: { dot: "bg-cyan-300", label: "Read" },
  edit: { dot: "bg-amber-300", label: "Edited" },
  verify: { dot: "bg-emerald-300", label: "Verified" },
};

const FILTER_WORDS: Record<string, string> = {
  cross_language: "across languages",
  production_to_test: "from shipping code into tests",
};

export function relativeTime(value: string, now = Date.now()): string {
  const time = new Date(value).getTime();
  if (!Number.isFinite(time)) return "now";
  const seconds = Math.max(0, Math.round((now - time) / 1000));
  if (seconds < 10) return "now";
  if (seconds < 60) return `${seconds}s ago`;
  if (seconds < 3600) return `${Math.floor(seconds / 60)}m ago`;
  if (seconds < 86400) return `${Math.floor(seconds / 3600)}h ago`;
  return `${Math.floor(seconds / 86400)}d ago`;
}

function lastEdit(value: string): string {
  const relative = relativeTime(value);
  return relative === "now" ? "just now" : relative;
}

/** Where a module's purpose line came from, stated plainly. */
export function purposeOrigin(module: CodeModule, now = Date.now()): string {
  if (module.purpose_kind === "generated") {
    const count = module.purpose_evidence?.length ?? 0;
    const when = module.purpose_at ? ` · ${relativeTime(module.purpose_at, now)}` : "";
    return `Generated by ${module.purpose_source} from ${count} ${count === 1 ? "file" : "files"}${when}`;
  }
  if (module.purpose_kind === "file") return `from ${module.purpose_source}, one of its most connected files`;
  return `from ${module.purpose_source}`;
}

/** Which index answered, stated plainly: `/code` is never Snapshot-exact. */
export function indexNote(context: CodeIndexContext | undefined): string {
  if (!context) return "";
  if (context.relationship_basis === "imports") return "Import-level relationships · precise references need LemonCrow Hosted";
  if (context.fallback) return "Legacy index · names resolved by match";
  const graph = context.readiness?.graph?.state;
  if (graph === "building") return "Current index · still building";
  if (context.readiness?.backend === "none" || context.backend === "unavailable") return "Index unavailable";
  return "Current index";
}

function RelationshipRows({
  rows,
  total,
  direction,
  empty,
  onOpen,
}: {
  rows: CodeRelationshipRow[];
  total: number;
  direction: "in" | "out";
  empty: string;
  onOpen: (path: string, line?: number) => void;
}) {
  const Icon = direction === "in" ? ArrowDownLeft : ArrowUpRight;
  if (!rows.length) return <p className="py-1 text-label text-muted-foreground">{empty}</p>;
  return (
    <>
      <InspectorList>
        {rows.map((row) => {
          const kinds = Object.entries(row.kinds).sort((a, b) => b[1] - a[1]).map(([kind, count]) => `${kind} ${count}`).join(" · ");
          return (
            <li key={row.path}>
              <InspectorRow
                onClick={() => onOpen(row.path, row.lines[0])}
                title={`${row.path}${row.lines.length ? `:${row.lines.join(", ")}` : ""}\n${kinds}`}
              >
                <Icon size={11} className={`shrink-0 ${direction === "in" ? "text-violet-300" : "text-cyan-300"}`} />
                <span className="min-w-0 flex-1 truncate text-label text-neutral-300">
                  {row.path.split("/").pop()}
                  {row.symbols.length > 0 && <span className="text-muted-foreground"> · {row.symbols.slice(0, 2).join(", ")}</span>}
                </span>
                <span className="shrink-0 text-micro tabular-nums text-muted-foreground">
                  {row.kind}
                  {row.weight > 1 ? ` ×${row.weight}` : ""}
                </span>
              </InspectorRow>
            </li>
          );
        })}
      </InspectorList>
      {total > rows.length && <p className="pt-1 text-caption text-muted-foreground">{total - rows.length} more, weaker links not shown.</p>}
    </>
  );
}

function ModuleRows({ rows, direction, onSelect }: { rows: ModuleLink[]; direction: "in" | "out"; onSelect: (id: string) => void }) {
  const Icon = direction === "in" ? ArrowDownLeft : ArrowUpRight;
  if (!rows.length) return <p className="py-1 text-label text-muted-foreground">None among the strongest module links.</p>;
  return (
    <InspectorList>
      {rows.slice(0, 20).map((row) => (
        <li key={row.id}>
          <InspectorRow onClick={() => onSelect(row.id)} title={row.id || "Repository root"}>
            <Icon size={11} className={`shrink-0 ${direction === "in" ? "text-violet-300" : "text-cyan-300"}`} />
            <span className="min-w-0 flex-1 truncate text-label text-neutral-300">{row.label}</span>
            <span className="shrink-0 text-micro tabular-nums text-muted-foreground">×{row.weight}</span>
          </InspectorRow>
        </li>
      ))}
    </InspectorList>
  );
}

function ReferenceList({ payload, loading, error, onOpen }: { payload: CodeMapReferences | null; loading: boolean; error: string | null; onOpen: (reference: CodeMapReference) => void }) {
  const shown = payload?.references ?? [];
  return (
    <Section title={`References${payload ? ` · ${payload.reference_count}` : ""}`} aside={payload?.truncated ? "partial" : undefined}>
      {loading ? (
        <div className="flex items-center gap-2 py-2 text-caption text-muted-foreground">
          <Loader2 size={11} className="animate-spin" /> Finding usages…
        </div>
      ) : error ? (
        <p className="py-1 text-caption leading-4 text-red-300/70">{error}</p>
      ) : shown.length ? (
        <div className="-mx-1.5 space-y-0.5">
          {shown.slice(0, 40).map((reference, index) => (
            <UiButton
              unstyled
              key={`${reference.path}:${reference.line}:${reference.column}:${index}`}
              type="button"
              onClick={() => onOpen(reference)}
              className="w-full rounded-md border-l-2 border-transparent px-2 py-1.5 text-left transition hover:bg-muted"
              title={`${reference.path}:${reference.line}`}
            >
              <div className="flex min-w-0 items-center gap-2">
                <Search size={10} className="shrink-0 text-amber-300/70" />
                <span className="min-w-0 flex-1 truncate text-caption text-neutral-300">{reference.path}</span>
                <span className="shrink-0 font-mono text-micro tabular-nums text-amber-300/70">L{reference.line}</span>
              </div>
              {reference.snippet && <code className="mt-1 block truncate font-mono text-micro text-muted-foreground">{reference.snippet.trim()}</code>}
            </UiButton>
          ))}
        </div>
      ) : payload ? (
        <p className="py-1 text-label text-muted-foreground">No usages found.</p>
      ) : null}
    </Section>
  );
}

export interface CodeInspectorProps {
  subject: InspectorSubject | null;
  relationships: CodeRelationships | null;
  relationshipsLoading: boolean;
  relationshipsError: string | null;
  references: CodeMapReferences | null;
  referencesLoading: boolean;
  referencesError: string | null;
  events: readonly CodeMapActivityEvent[];
  activityHost: string | null;
  change: CodeChangedFile | undefined;
  changes: CodeChanges | null;
  marks: ReadonlyMap<string, string>;
  reviewBusy: boolean;
  reviewError: string | null;
  onOpenPath: (path: string, line?: number) => void;
  onOpenReference: (reference: CodeMapReference) => void;
  onOpenActivity: (event: CodeMapActivityEvent) => void;
  onSelectModule: (id: string) => void;
  onFocusModule: (id: string) => void;
  /** Absent where Review capture from Code is not served (a local Dashboard). */
  onReview?: (scope: ReviewScope) => void;
  /** Absent where Code Ask is not served. */
  onAsk?: () => void;
  /** Precise references come from the private engine; a local Dashboard has none. */
  referencesAvailable?: boolean;
  /** Recorded re-edits of the selected file in the hotspot window. */
  hotspot?: CodeHotspot;
  hotspotDays?: number;
  /** The internal model that can describe a module on request, if any. */
  purposeModel?: string;
  purposeBusy?: boolean;
  purposeError?: string | null;
  onDescribeModule?: (id: string) => void;
}

export default function CodeInspector({
  subject,
  relationships,
  relationshipsLoading,
  relationshipsError,
  references,
  referencesLoading,
  referencesError,
  events,
  activityHost,
  change,
  changes,
  marks,
  reviewBusy,
  reviewError,
  onOpenPath,
  onOpenReference,
  onOpenActivity,
  onSelectModule,
  onFocusModule,
  onReview,
  onAsk,
  referencesAvailable = true,
  hotspot,
  hotspotDays = 7,
  purposeModel = "",
  purposeBusy = false,
  purposeError = null,
  onDescribeModule,
}: CodeInspectorProps) {
  if (!subject) {
    return (
      <aside className="border-t border-border bg-background/60 p-4 xl:border-l xl:border-t-0" aria-label="Inspector">
        <div className="text-caption font-semibold uppercase tracking-widest text-neutral-400">Inspector</div>
        <p className="mt-2 text-xs leading-5 text-muted-foreground">Select a file, symbol, or module to see what uses it, what it uses, and who is working on it.</p>
      </aside>
    );
  }

  if (subject.kind === "module") {
    const module = subject.module;
    return (
      <aside className="min-h-0 overflow-y-auto overscroll-contain border-t border-border bg-background/60 xl:border-l xl:border-t-0" aria-label="Inspector">
        <InspectorFacts glyph={<Folder size={15} className="text-cyan-200" />} kicker={module.package ? "package" : "module"} title={module.path || "(repository root)"} titleHint={module.path}>
          <div className="mt-1 text-caption text-muted-foreground">
            {module.files.toLocaleString()} files · {module.symbols.toLocaleString()} symbols
            {module.changed ? ` · ${module.changed} uncommitted` : ""}
          </div>
          {module.purpose && (
            <p className="mt-2 text-label leading-4 text-neutral-400">
              {module.purpose}
              <span className="block text-micro text-muted-foreground" title={module.purpose_evidence?.join("\n")}>
                {purposeOrigin(module)}
              </span>
            </p>
          )}
          <div className="mt-3 flex flex-wrap gap-1.5">
            <UiButton type="button" size="xs" variant="outline" onClick={() => onFocusModule(module.id)}>
              Map this module
            </UiButton>
            {purposeModel && onDescribeModule && module.purpose_kind !== "declared" && (
              <UiButton
                type="button"
                size="xs"
                variant="ghost"
                disabled={purposeBusy}
                onClick={() => onDescribeModule(module.id)}
                title={`Ask ${purposeModel} for one line on this module, from its paths, the files' own statements, and the names they define.`}
              >
                {purposeBusy ? <Loader2 size={10} className="animate-spin" /> : <Sparkles size={10} />}
                {module.purpose_kind === "generated" ? "Describe again" : `Describe with ${purposeModel}`}
              </UiButton>
            )}
          </div>
          {purposeError && <p className="mt-2 text-caption leading-4 text-red-300/80">{purposeError}</p>}
        </InspectorFacts>
        <Section title={`Used by · ${subject.usedBy.length}`}>
          <ModuleRows rows={subject.usedBy} direction="in" onSelect={onSelectModule} />
        </Section>
        <Section title={`Uses · ${subject.uses.length}`}>
          <ModuleRows rows={subject.uses} direction="out" onSelect={onSelectModule} />
        </Section>
        {module.top_files.length > 0 && (
          <Section title="Most connected files">
            <InspectorList>
              {module.top_files.map((path) => (
                <li key={path}>
                  <InspectorRow onClick={() => onOpenPath(path)} title={path}>
                    <FileTypeIcon path={path} size={12} />
                    <span className="min-w-0 flex-1 truncate text-label text-neutral-300">{path.split("/").pop()}</span>
                  </InspectorRow>
                </li>
              ))}
            </InspectorList>
          </Section>
        )}
      </aside>
    );
  }

  const node = subject.node;
  const pathEvents = [...events].reverse().filter((event) => event.path === node.path);
  const authors = change ? (changes?.sessions ?? []).filter((session) => change.sessions.includes(session.id)) : [];
  const note = indexNote(relationships?.context);
  const filtered = Object.entries(relationships?.filtered ?? {}).filter(([, count]) => count > 0);
  const pending = relationships?.context.readiness?.graph?.state === "building" && !relationships.used_by.length && !relationships.uses.length;
  const usesEmpty =
    subject.kind === "symbol" && relationships && !relationships.uses_attributed
      ? "Calls out of a symbol are shown only when both indexes hold this file exactly as it is on disk."
      : "The index records nothing this uses.";

  return (
    <aside className="min-h-0 overflow-y-auto overscroll-contain border-t border-border bg-background/60 xl:border-l xl:border-t-0" aria-label="Inspector">
      <InspectorFacts
        glyph={subject.kind === "file" ? <FileTypeIcon path={node.path} size={15} /> : <CircleDot size={15} className="text-cyan-200" />}
        kicker={`${subject.kind === "file" ? node.file_type || "file" : node.kind}${node.language ? ` · ${node.language}` : ""}`}
        title={subject.kind === "file" ? node.label : node.qualified_name || node.label}
        titleHint={subject.kind === "file" ? node.path : node.qualified_name || node.label}
        location={`${node.path}${subject.range ? `:${displayRange(subject.range)}` : ""}`}
        headerAction={onAsk ? <UiButton type="button" size="xs" variant="ghost" onClick={onAsk} aria-label={`Ask about ${node.label}`}><Sparkles size={12} /> Ask</UiButton> : undefined}
      >
        {change && (
          <div className="mt-2 text-caption text-amber-200/90">
            Uncommitted · +{change.additions} −{change.deletions}
            {change.shared ? " · shared" : ""}
          </div>
        )}
      </InspectorFacts>

      <Section title={`Used by · ${relationships?.used_by_total ?? "…"}`} aside={note}>
        {relationshipsLoading && !relationships ? (
          <div className="flex items-center gap-2 py-2 text-caption text-muted-foreground">
            <Loader2 size={11} className="animate-spin" /> Reading the index…
          </div>
        ) : relationshipsError ? (
          <p className="py-1 text-caption leading-4 text-red-300/70">{relationshipsError}</p>
        ) : relationships ? (
          <RelationshipRows
            rows={relationships.used_by}
            total={relationships.used_by_total}
            direction="in"
            empty={pending ? "The index is still building its links; this fills in when it is ready." : "Nothing in the index uses this."}
            onOpen={onOpenPath}
          />
        ) : null}
      </Section>
      <Section title={`Uses · ${relationships?.uses_total ?? "…"}`}>
        {relationships && !relationshipsError ? (
          <RelationshipRows rows={relationships.uses} total={relationships.uses_total} direction="out" empty={pending ? "Still building." : usesEmpty} onOpen={onOpenPath} />
        ) : relationshipsLoading ? (
          <p className="py-1 text-label text-muted-foreground">…</p>
        ) : null}
        {filtered.length > 0 && (
          <p className="mt-1.5 text-caption leading-4 text-muted-foreground">
            Left out {filtered.map(([reason, count]) => `${count} name ${count === 1 ? "match" : "matches"} ${FILTER_WORDS[reason] ?? reason}`).join(", ")}.
          </p>
        )}
      </Section>

      {subject.kind === "symbol" && referencesAvailable && <ReferenceList payload={references} loading={referencesLoading} error={referencesError} onOpen={onOpenReference} />}

      <Section title="Activity" aside={activityHost ? `following ${activityHost}` : undefined}>
        {hotspot && (
          <p className="pb-1.5 text-label leading-4 text-neutral-400" title={hotspot.sessions.join("\n")}>
            Agents edited this file {hotspot.edits} times {windowPhrase(hotspotDays)}, in {hotspot.sessions.length}{" "}
            {hotspot.sessions.length === 1 ? "session" : "sessions"}; the last {lastEdit(hotspot.last_at)}.
          </p>
        )}
        {pathEvents.length ? (
          <InspectorList aria-label="Agent activity on this file">
            {pathEvents.slice(0, 8).map((event) => (
              <li key={event.id}>
                <InspectorRow className="py-1" onClick={() => onOpenActivity(event)}>
                  <span className={`h-1.5 w-1.5 shrink-0 rounded-full ${ACTIVITY_TONE[event.kind].dot}`} />
                  <span className="min-w-0 flex-1 truncate text-label text-neutral-300">
                    {event.label}
                    {event.line ? ` · L${event.line}` : ""}
                  </span>
                  <time className="shrink-0 text-micro text-muted-foreground" dateTime={event.at}>
                    {relativeTime(event.at)}
                  </time>
                </InspectorRow>
              </li>
            ))}
          </InspectorList>
        ) : (
          <p className="py-1 text-label text-muted-foreground">No agent activity on this file in the followed session.</p>
        )}
      </Section>

      <Section title="Changes">
        {change ? (
          <div className="space-y-2">
            <p className="text-label leading-4 text-neutral-400">
              {authors.length
                ? `Edited by ${authors.map((session) => `${marks.get(session.id) ?? ""} ${sessionLabel(session)}`.trim()).join(", ")}.`
                : "No session recorded editing this file."}
            </p>
            {onReview && (
              <div className="flex flex-wrap gap-1.5">
                {authors.length ? (
                  authors.map((session) => (
                    <UiButton key={session.id} type="button" size="xs" variant="outline" disabled={reviewBusy} onClick={() => onReview({ session: session.id })}>
                      {reviewBusy ? <Loader2 size={10} className="animate-spin" /> : <GitPullRequest size={10} />}
                      Review session {marks.get(session.id) ?? ""}
                    </UiButton>
                  ))
                ) : (
                  <UiButton type="button" size="xs" variant="outline" disabled={reviewBusy} onClick={() => onReview({ paths: [node.path] })}>
                    {reviewBusy ? <Loader2 size={10} className="animate-spin" /> : <GitPullRequest size={10} />}
                    Review this file
                  </UiButton>
                )}
              </div>
            )}
            {reviewError && <p className="text-caption leading-4 text-red-300/80">{reviewError}</p>}
          </div>
        ) : (
          <p className="py-1 text-label text-muted-foreground">No uncommitted changes.</p>
        )}
      </Section>

    </aside>
  );
}
